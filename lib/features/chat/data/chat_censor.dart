  ])
    RegExp(
      '(?<![\\p{L}\\p{N}_])${RegExp.escape(word)}'
      '(?![\\p{L}\\p{N}_])',
      caseSensitive: false,
      unicode: true,
    ),
];

String censorChatMessage(String message) {
  if (!_chatCensoredWords.any((word) => word.hasMatch(message))) {
    return message;
  }
  return message.replaceAll(RegExp(r'\S'), '#');
}
