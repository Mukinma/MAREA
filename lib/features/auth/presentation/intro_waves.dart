  @override
  void paint(Canvas canvas, Size size) {
    canvas.save();
    canvas.scale(size.width / 9055, size.height / 2063);
    // The SVG layers share edges: moving them together preserves those seams.
    canvas.translate(0, drift * 42);
    for (var i = 0; i < _layers.length; i++) {
      canvas.drawPath(_layers[i].$2, Paint()..color = _layers[i].$1);
      // Cover subpixel antialiasing gaps between adjoining vector paths.
      canvas.drawPath(
        _layers[i].$2,
        Paint()
          ..color = _layers[i].$1
          ..style = PaintingStyle.stroke
          ..strokeWidth = 12,
      );
    }
    canvas.restore();
  }

  @override
  bool shouldRepaint(IntroWavesPainter oldDelegate) =>
      drift != oldDelegate.drift;
